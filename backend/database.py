"""Database adapter for ARFH portal upload audit logs.

Uses Supabase PostgreSQL when DATABASE_URL is configured, and a local SQLite
file only for development when no DATABASE_URL exists.
"""
import os
import sqlite3
from pathlib import Path


class PostgresCursor:
    def __init__(self, cursor):
        self._cursor = cursor

    def execute(self, sql, params=None):
        # Existing app.py uses SQLite-style ? positional placeholders.
        sql = sql.replace('?', '%s')
        self._cursor.execute(sql, params or ())
        return self

    def fetchall(self):
        return self._cursor.fetchall()


class PostgresConnection:
    def __init__(self, connection):
        self._connection = connection

    def cursor(self):
        from psycopg.rows import dict_row
        return PostgresCursor(self._connection.cursor(row_factory=dict_row))

    def commit(self):
        self._connection.commit()

    def close(self):
        self._connection.close()


def get_connection():
    url = os.getenv('DATABASE_URL', '').strip()
    if url:
        import psycopg
        # Keep the existing app's unqualified upload_logs queries scoped to private schema.
        conn = psycopg.connect(url, connect_timeout=15, options='-c search_path=arfh_private,public')
        return PostgresConnection(conn)

    db_path = Path(__file__).resolve().parent / 'upload_logs.sqlite3'
    conn = sqlite3.connect(str(db_path))
    conn.row_factory = sqlite3.Row
    return conn


def init_db():
    url = os.getenv('DATABASE_URL', '').strip()
    if url:
        import psycopg
        with psycopg.connect(url, connect_timeout=15) as conn:
            with conn.cursor() as cur:
                cur.execute('CREATE SCHEMA IF NOT EXISTS arfh_private')
                cur.execute('''CREATE TABLE IF NOT EXISTS arfh_private.upload_logs (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
                    facility_name TEXT, lga TEXT, state TEXT,
                    report_year TEXT, report_month TEXT, target_tab TEXT,
                    quarter TEXT, workbook_id TEXT, matched_row INTEGER,
                    uploaded_filename TEXT, updated_cells INTEGER,
                    status TEXT, message TEXT,
                    attendance_total DOUBLE PRECISION,
                    screened_total DOUBLE PRECISION,
                    presumptive_total DOUBLE PRECISION,
                    diagnosed_total DOUBLE PRECISION,
                    notified_total DOUBLE PRECISION
                )''')
                cur.execute('CREATE INDEX IF NOT EXISTS idx_arfh_upload_logs_created_at ON arfh_private.upload_logs (created_at DESC)')
                cur.execute('''CREATE TABLE IF NOT EXISTS arfh_private.facility_performance (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
                    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
                    state TEXT NOT NULL, lga TEXT NOT NULL, facility_name TEXT NOT NULL,
                    report_year TEXT NOT NULL, report_month TEXT NOT NULL,
                    upload_log_id BIGINT REFERENCES arfh_private.upload_logs(id),
                    indicators_json TEXT NOT NULL,
                    UNIQUE (state, lga, facility_name, report_year, report_month)
                )''')
                cur.execute('CREATE INDEX IF NOT EXISTS idx_arfh_performance_period ON arfh_private.facility_performance (state, report_year, report_month)')
                cur.execute('REVOKE ALL ON arfh_private.facility_performance FROM PUBLIC, anon, authenticated')
                # Keep log table out of browser-facing anon/authenticated roles.
                cur.execute('REVOKE ALL ON arfh_private.upload_logs FROM PUBLIC, anon, authenticated')
        return

    conn = get_connection()
    conn.execute('''CREATE TABLE IF NOT EXISTS upload_logs (
        id INTEGER PRIMARY KEY AUTOINCREMENT,
        created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
        facility_name TEXT, lga TEXT, state TEXT,
        report_year TEXT, report_month TEXT, target_tab TEXT,
        quarter TEXT, workbook_id TEXT, matched_row INTEGER,
        uploaded_filename TEXT, updated_cells INTEGER,
        status TEXT, message TEXT,
        attendance_total REAL, screened_total REAL,
        presumptive_total REAL, diagnosed_total REAL,
        notified_total REAL
    )''')
    conn.execute('''CREATE TABLE IF NOT EXISTS facility_performance (
        id INTEGER PRIMARY KEY AUTOINCREMENT,
        created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
        updated_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
        state TEXT NOT NULL, lga TEXT NOT NULL, facility_name TEXT NOT NULL,
        report_year TEXT NOT NULL, report_month TEXT NOT NULL,
        upload_log_id INTEGER, indicators_json TEXT NOT NULL,
        UNIQUE (state, lga, facility_name, report_year, report_month)
    )''')
    conn.commit()
    conn.close()
